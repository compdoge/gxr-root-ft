/* Dormant: no probe event recently, so there is nothing to parse and nothing to
   say past a keepalive. Dormant from the start too (g_lastDataMs is 0 until the
   first event), which is the normal state for a headset nobody is wearing.
   The dormant period is never faster than the user's own --tx-hz, so a slow
   stream (--tx-hz 5) stays slow while idle instead of speeding up to 10 Hz. */
static int at_least(int a, int b) { return a > b ? a : b; }
static int idle_now(void) { return g_lastDataMs == 0 || (now_ms() - g_lastDataMs) > IDLE_MS; }
static int poll_ms(void) { return idle_now() ? at_least(IDLE_POLL_MS, tx_period_ms()) : tx_period_ms(); }
static int tx_gap_ms(void) { return idle_now() ? at_least(1000 / IDLE_TX_HZ, tx_period_ms()) : tx_period_ms(); }

static void tx_send(void) {
    long long now = now_ms();
    if (!g_stateOk) return;
    if (now - g_lastDataMs > TX_HOLD_MS) {
        /* Device has gone quiet: send a relaxed, forward-looking frame rather than
           replaying a frozen expression -- but keep the link alive either way. */
        float ue2[UE_MAX]; memset(ue2, 0, sizeof(ue2));
        float t2[TAIL_N]; memcpy(t2, g_tail, sizeof(t2));
        t2[T_LOpen] = 1.0f; t2[T_ROpen] = 1.0f;
        t2[T_LPitch] = 0.0f; t2[T_LYaw] = 0.0f;
        t2[T_RPitch] = 0.0f; t2[T_RYaw] = 0.0f;
        send_uniexpr(ue2, t2);
    } else {
        send_uniexpr(g_ue, g_tail);
    }
    g_txCount++;
    g_lastTxMs = now;
}

static int cmpf(const void *a, const void *b) {
    float x = *(const float *)a, y = *(const float *)b;
    return (x > y) - (x < y);
}

/* ---- tongue extras: exact 11->5 mapper + calibration readouts ---- */
static void tongue_mlp(const float x[TONGUE_IN], float out[TONGUE_DOF]) {
    static float h1[TONGUE_H1], h2[TONGUE_H2], h3[TONGUE_H3];
    for (int j = 0; j < TONGUE_H1; j++) {
        float s = TONGUE_B1[j]; const float *w = TONGUE_W1[j];
        for (int i = 0; i < TONGUE_IN; i++) s += w[i] * x[i];
        h1[j] = s > 0.0f ? s : 0.0f;
    }
    for (int j = 0; j < TONGUE_H2; j++) {
        float s = TONGUE_B2[j]; const float *w = TONGUE_W2[j];
        for (int i = 0; i < TONGUE_H1; i++) s += w[i] * h1[i];
        h2[j] = s > 0.0f ? s : 0.0f;
    }
    for (int j = 0; j < TONGUE_H3; j++) {
        float s = TONGUE_B3[j]; const float *w = TONGUE_W3[j];
        for (int i = 0; i < TONGUE_H2; i++) s += w[i] * h2[i];
        h3[j] = s > 0.0f ? s : 0.0f;
    }
    for (int j = 0; j < TONGUE_DOF; j++) {
        float s = TONGUE_B4[j]; const float *w = TONGUE_W4[j];
        for (int i = 0; i < TONGUE_H3; i++) s += w[i] * h3[i];
        out[j] = 1.0f / (1.0f + expf(-s));
    }
}
static float tongue_readout(const float x[TONGUE_IN], const float dof[TONGUE_DOF],
                            const float axis[TONGUE_IN], const float coef[TONGUE_DOF],
                            float intercept) {
    float s = intercept;
    for (int i = 0; i < TONGUE_IN; i++) s += axis[i] * x[i];
    for (int i = 0; i < TONGUE_DOF; i++) s += coef[i] * dof[i];
    return s;
}

/* ---------------- dilation range state ----------------
   Files live in the module directory (--state-dir; supervise.sh passes it):
     dilmin, dilmax  the learned envelope, written when an extreme is committed
     dillock         present = frozen: emit exactly this window, learn nothing
   The WebUI's Lock/Unlock writes the marker and restarts the relay, so the
   frozen values are always the last ones the relay persisted. */
static void state_path(char *buf, size_t n, const char *name) {
    if (!g_stateDir || !g_stateDir[0]) { buf[0] = '\0'; return; }
    snprintf(buf, n, "%s/%s", g_stateDir, name);
}

static int state_read_float(const char *name, float *out) {
    char p[512];
    state_path(p, sizeof(p), name);
    if (!p[0]) return -1;
    FILE *f = fopen(p, "r");
    if (!f) return -1;
    float v = 0.0f;
    int got = (fscanf(f, "%f", &v) == 1);
    fclose(f);
    if (!got || !(v > 0.0f) || v > 100.0f) return -1;   /* junk never becomes a seed */
    *out = v;
    return 0;
}

static int state_exists(const char *name) {
    char p[512];
    state_path(p, sizeof(p), name);
    return p[0] && access(p, F_OK) == 0;
}

static void state_write_float(const char *name, float v) {
    static int warned;
    char p[512], tmp[544];
    state_path(p, sizeof(p), name);
    if (!p[0]) return;
    snprintf(tmp, sizeof(tmp), "%s.tmp", p);
    FILE *f = fopen(tmp, "w");
    if (!f) {
        if (!warned) { warned = 1; fprintf(stderr, "gxr_alvr: cannot write %s: %s\n", p, strerror(errno)); }
        return;
    }
    fprintf(f, "%.3f\n", (double)v);
    if (fclose(f) != 0 || rename(tmp, p) != 0) {
        if (!warned) { warned = 1; fprintf(stderr, "gxr_alvr: cannot save %s: %s\n", p, strerror(errno)); }
        unlink(tmp);   /* never leave a half-written file */
        return;
    }
    chmod(p, 0644);
}

static void state_unlink(const char *name) {
    char p[512];
    state_path(p, sizeof(p), name);
    if (p[0]) unlink(p);
}

static float median_of(const float *src, int n) {
    float tmp[DIL_SEED_BUF];
    if (n <= 0) return 0.0f;
    if (n > (int)(sizeof(tmp) / sizeof(tmp[0]))) n = (int)(sizeof(tmp) / sizeof(tmp[0]));
    memcpy(tmp, src, (size_t)n * sizeof(float));
    qsort(tmp, (size_t)n, sizeof(float), cmpf);
    return tmp[n / 2];
}

static void dil_load(void) {
    long long now = now_ms();
    float lo = 0.0f, hi = 0.0f;
    int haveLo = state_read_float("dilmin", &lo) == 0;
    int haveHi = state_read_float("dilmax", &hi) == 0;
    g_dilLock = state_exists("dillock");
    /* hi - lo <= 5 mm rejects a pair torn between two commits (the files are
       written one at a time); a real envelope is well under that. */
    if (haveLo && haveHi && hi > lo && hi - lo <= 5.0f) {
        g_minMm = lo; g_maxMm = hi;
        g_winLoaded = 1; g_winSaveable = 1; g_seeded = 1;
        g_winMinCand = lo; g_winMaxCand = hi;
        g_winMinMs = g_winMaxMs = now;
        g_minTouchMs = g_maxTouchMs = now;
        fprintf(stderr, "gxr_alvr: dilation range loaded: %.3f..%.3f mm%s\n",
                (double)lo, (double)hi, g_dilLock ? " (locked)" : " (learning continues)");
    } else if (g_dilLock) {
        /* Never leave a marker that the UI trusts while the relay is learning:
           a copied or interrupted pair would otherwise report "locked" forever. */
        state_unlink("dillock");
        g_dilLock = 0;
        fprintf(stderr, "gxr_alvr: dillock present but dilmin/dilmax are missing or invalid; "
                        "removed it and learning the range instead\n");
    }
}

static void dil_save(void) {
    if (!g_stateDir || g_dilLock || !g_have_pupil || !g_seeded || !g_winSaveable) return;
    state_write_float("dilmin", g_minMm);
    state_write_float("dilmax", g_maxMm);
}

/* Keep a short history of CLEAN samples (~2 min) plus when each committed
   extreme was last approached, which is all the healing check needs. */
static void dil_history(float mm, int clean, long long now) {
    if (!clean || now - g_healSampleMs < DIL_HEAL_SAMPLE_MS) return;
    g_healSampleMs = now;
    g_healRing[g_healIdx] = mm;
    g_healRingMs[g_healIdx] = now;
    g_healIdx = (g_healIdx + 1) % DIL_HEAL_RING;
    if (g_healN < DIL_HEAL_RING) g_healN++;
    if (mm <= g_minMm + DIL_HEAL_NEAR) g_minTouchMs = now;
    if (mm >= g_maxMm - DIL_HEAL_NEAR) g_maxTouchMs = now;
}

/* A stray that still got committed would otherwise stay in the window forever
   (the envelope only grows). If the user has not come near an extreme for
   DIL_HEAL_STALE_MS, move it halfway toward the recent p2/p98 - slowly, so a
   single odd window cannot yank the range around. */
static void dil_heal(long long now) {
    if (g_dilLock || !g_seeded || g_healN < DIL_HEAL_RING / 4) return;
    if (now - g_healCheckMs < DIL_HEAL_PERIOD_MS) return;
    g_healCheckMs = now;
    float tmp[DIL_HEAL_RING];
    int m = 0;
    for (int i = 0; i < g_healN; i++) {
        int q = (g_healIdx - 1 - i + 2 * DIL_HEAL_RING) % DIL_HEAL_RING;
        if (now - g_healRingMs[q] > DIL_HEAL_WINDOW_MS) continue;
        tmp[m++] = g_healRing[q];
    }
    if (m < 16) return;
    qsort(tmp, (size_t)m, sizeof(float), cmpf);
    float p2 = tmp[(int)(0.02f * (float)(m - 1) + 0.5f)];
    float p98 = tmp[(int)(0.98f * (float)(m - 1) + 0.5f)];
    /* A stable pupil is not evidence that the range collapsed. Without this gate
       an hour of sitting still in steady light healed a 3.0..6.0 window down to a
       sliver, which makes the avatar wildly sensitive. */
    if (p98 - p2 < DIL_HEAL_MIN_SPAN) return;
    int moved = 0;
    float lo = g_minMm, hi = g_maxMm;
    if (now - g_minTouchMs > DIL_HEAL_STALE_MS && p2 > lo + DIL_HEAL_GAP) {
        float next = lo + DIL_HEAL_STEP * (p2 - lo);
        if (next > hi - DIL_HEAL_MIN_SPAN) next = hi - DIL_HEAL_MIN_SPAN;
        if (next > lo) { lo = next; g_minTouchMs = now; moved = 1; }
    }
    if (now - g_maxTouchMs > DIL_HEAL_STALE_MS && p98 < hi - DIL_HEAL_GAP) {
        float next = hi + DIL_HEAL_STEP * (p98 - hi);
        if (next < lo + DIL_HEAL_MIN_SPAN) next = lo + DIL_HEAL_MIN_SPAN;
        if (next < hi) { hi = next; g_maxTouchMs = now; moved = 1; }
    }
    if (moved) {
        fprintf(stderr, "gxr_alvr: dilation range healed %.3f..%.3f -> %.3f..%.3f mm "
                        "(recent p2/p98 %.3f/%.3f)\n",
                (double)g_minMm, (double)g_maxMm, (double)lo, (double)hi,
                (double)p2, (double)p98);
        g_minMm = lo; g_maxMm = hi;
        g_winMinCand = lo; g_winMaxCand = hi;
        g_winMinMs = g_winMaxMs = now;
        dil_save();
    }
}

static void compute_and_send(void) {
    long long now = now_ms();
    g_computeCount++;
    float *ue = g_ue, *tail = g_tail; memset(ue, 0, sizeof(g_ue));

    /* 1) 68 -> UE */
    int haveFace = (now - g_face_ms) <= FRESH_MS;
    if (haveFace) for (int i = 0; i < NTAB; i++) ue[FACE68_TO_UE[i].ue] = g_face[FACE68_TO_UE[i].face];

    /* 2) lip-suck compensation (as in RootedLinkFT.UpdateFaceTracking) */
    ue[UE_LipSuckUpperLeft]  = fminf(1.0f - powf(fmaxf(ue[UE_MouthUpperLeft], 0.0f), LIP_SUCK_EXP), ue[UE_LipSuckUpperLeft]);
    ue[UE_LipSuckUpperRight] = fminf(1.0f - powf(fmaxf(ue[UE_MouthUpperRight], 0.0f), LIP_SUCK_EXP), ue[UE_LipSuckUpperRight]);

    /* 3) un-clamped jaw override (only while the vendor clamp drives it) */
    int haveJaw = (now - g_jaw_ms) <= FRESH_MS;
    if (haveJaw) {
        float raw = g_jaw[0], to = g_jaw[1], tu = g_jaw[2], td = g_jaw[3];
        int clampActive = (to > JAW_CLAMP_ACTIVE || tu > JAW_CLAMP_ACTIVE || td > JAW_CLAMP_ACTIVE);
        if (!clampActive) {
            g_jawHist[g_jawIdx] = raw; g_jawIdx = (g_jawIdx + 1) % JAW_HIST;
            if (g_jawN < JAW_HIST) g_jawN++;
        }
        if (g_jawN >= JAW_MIN_SAMPLES && now - g_jawNeutralMs > JAW_NEUTRAL_PERIOD_MS) {
            g_jawNeutralMs = now;
            float tmp[JAW_HIST]; memcpy(tmp, g_jawHist, g_jawN * sizeof(float));
            qsort(tmp, g_jawN, sizeof(float), cmpf);
            g_jawNeutral = tmp[(int)(0.05f * (g_jawN - 1))];
            if (g_jawNeutral > JAW_NEUTRAL_MAX) g_jawNeutral = JAW_NEUTRAL_MAX;
            if (g_jawNeutral < JAW_NEUTRAL_MIN) g_jawNeutral = JAW_NEUTRAL_MIN;
        }
        float shipped = ue[UE_JawOpen];
        int inBand = (shipped > JAW_BAND_LO && shipped < JAW_BAND_HI);
        if (clampActive || inBand) {
            float denom = fmaxf(1.0f - g_jawNeutral, JAW_DENOM_FLOOR);
            ue[UE_JawOpen] = clampf((raw - g_jawNeutral) / denom, 0.0f, 1.0f);
        }
    }

    /* 4) tail */
    memset(tail, 0, sizeof(g_tail));
    tail[T_Version] = 1.0f;
    /* Until the first pupil detection these are what the PC sees: a plausible
       4.5 mm inside a 3..6 window. Without them a frame sent before the first
       pupil arrived carried pupil=0 with min=max=0, i.e. (0-0)/(0-0), which the
       next page of this story knows as a NaN. Now that dir/pten events recompute
       the frame, that frame is reachable at every session start. */
    tail[T_MinDil] = 3.0f; tail[T_MaxDil] = 6.0f;
    tail[T_LPupil] = 4.5f; tail[T_RPupil] = 4.5f;

    if (haveFace) {
        /* eyes_closed (face 12/13) is the raw value: the device folds the lid
           tightener into it later, in its own EyeWinkPostprocessor, and our uprobe
           reads it BEFORE that. Verified by RE: raw eyes_closed reaches exactly
           1.0 on a full closure (results/eye-postprocessing-re.md). So emit the raw
           openness, and let the squint travel as its own expression (FACE68_TO_UE
           maps face 28/29 -> UE_EyeSquint{Left,Right}) -- but restore the one
           thing that fold was actually needed for: a deliberate wink, which the
           raw value under-reports (see WINK_GAP). */
        float closedL = clampf(g_face[F_EYES_CLOSED_L], 0.0f, 1.0f);
        float closedR = clampf(g_face[F_EYES_CLOSED_R], 0.0f, 1.0f);
        if (WINK_GAP > 0.0f) {
            float dtms = (float)(now - g_winkMs); g_winkMs = now;
            if (dtms <= 0.0f || dtms > 500.0f) dtms = 100.0f;   /* first frame, or after a gap */
            float step = dtms / fmaxf(WINK_MS, 1.0f);
            /* Gate on the wink SHAPE, using the raw pair before either is folded:
               this eye closing while the other stays open. Both eyes closing (a
               blink) or both narrowing (a squint) keep the gap near zero, so
               nothing below fires for them -- which is what the old unconditional
               fold got wrong. A ramp (not a step) means a sustained wink closes all
               the way while a passing one-eye asymmetry only gets a partial fold. */
            int gateL = (closedL - closedR) > WINK_GAP;
            int gateR = (closedR - closedL) > WINK_GAP;
            g_winkBoost[0] = gateL ? fminf(g_winkBoost[0] + step, 1.0f)
                                   : fmaxf(g_winkBoost[0] - 2.0f * step, 0.0f);
            g_winkBoost[1] = gateR ? fminf(g_winkBoost[1] + step, 1.0f)
                                   : fmaxf(g_winkBoost[1] - 2.0f * step, 0.0f);
            closedL += (1.0f - closedL) * g_winkBoost[0];
            closedR += (1.0f - closedR) * g_winkBoost[1];
        }
        tail[T_LOpen] = 1.0f - closedL;
        tail[T_ROpen] = 1.0f - closedR;
    } else {
        /* No face frame yet, or the expression stream stopped. The UE block above
           is all zeros, which is a NEUTRAL face, so the lids must be open too.
           Leaving the memset's 0 here used to be unreachable (compute ran only
           right after a face frame); now that dir/pten events also recompute, it
           would shut the avatar's eyes at session start and during any stall. */
        tail[T_LOpen] = 1.0f; tail[T_ROpen] = 1.0f;
    }

    /* 3b) pupil: per eye, smoothed, with a drift-based fallback so a wink no
       longer steps or jitters the dilation. The probe returns two candidate
       detections per eye -- idx 0/1 = LEFT, 2/3 = RIGHT (confirmed on-device:
       the closed lid collapses that eye's detections to ~1 mm while the other
       eye stays ~4 mm, and the closed eye's detections KEEP ARRIVING, so
       freshness alone can't tell them apart). Each eye's largest candidate is
       taken (a lid occludes -> a smaller fit) and low-pass filtered, because a
       single eye is noisier than the two-eye average. A wink is detected by the
       eyes disagreeing (with hysteresis, and confirmed by a shut lid); the
       still-open eye then drives the value as its DRIFT from the last
       both-eyes-open pair average -- so dropping one lid neither steps the
       emitted dilation nor injects that eye's noise. Only a full blink with no
       usable eye holds (last good value, never 0). Because the emitted value is
       drift-calibrated and continuous, the min/max envelope can follow it even
       through a wink, and the emitted window is still forced to contain the
       emitted pupil (VRCFT pins dilation to 0 when pupil <= min). */
    float raw[2] = { 0.0f, 0.0f };
    for (int i = 0; i < 4; i++) {                       /* 0/1 = left, 2/3 = right */
        int e = i >> 1;
        if (!g_det_ok[i] || (now - g_det_ms[i]) > PUPIL_DET_FRESH_MS) continue;
        if (g_det_conf[i] < PUPIL_MIN_CONF) continue;
        float ax = fmaxf(g_det[i][2], g_det[i][3]);
        if (ax <= 0.0f) continue;   /* no ellipse at all: junk, don't clamp it into the band */
        float d = clampf(2.0f * ax * PUPIL_MM_SCALE, PUPIL_MIN_MM, PUPIL_MAX_MM);
        if (d > raw[e]) raw[e] = d;
    }
    int eyeOpen[2];
    eyeOpen[0] = !haveFace || (tail[T_LOpen] >= PUPIL_OPEN_GATE);
    eyeOpen[1] = !haveFace || (tail[T_ROpen] >= PUPIL_OPEN_GATE);
    float dt = (float)(now - g_emaMs); g_emaMs = now;
    float alpha = (dt > 0.0f) ? (1.0f - expf(-dt / fmaxf(PUPIL_SMOOTH_MS, 1.0f))) : 0.0f;
    for (int e = 0; e < 2; e++) {
        if (now - g_eyeMs[e] > (long long)PUPIL_RELOCK_MS) { g_eyeHave[e] = 0; g_eyeOccl[e] = 0; }
        if (raw[e] <= 0.0f) continue;
        /* A shut lid over a collapsed eye, or an eye sitting well below the other,
           means it is occluded (a wink, or a full blink). */
        int lidCollapse = !eyeOpen[e] && g_eyeHave[e] && raw[e] < g_eyeS[e] - PUPIL_MAX_JUMP;
        if (!g_eyeHave[e]) { g_eyeS[e] = raw[e]; g_eyeHave[e] = 1; }
        else if (!g_eyeOccl[e])                         /* never fold occluded junk in */
            g_eyeS[e] += alpha * (raw[e] - g_eyeS[e]);
        g_eyeMs[e] = now;
        float ev = (raw[0] > 0.0f && raw[1] > 0.0f) ? (raw[1 - e] - raw[e]) : -1e9f;
        int wasOccl = g_eyeOccl[e];
        if (g_eyeOccl[e]) { if (ev < PUPIL_EYE_CLEAR && !lidCollapse) g_eyeOccl[e] = 0; }
        else if (ev > PUPIL_EYE_GAP || lidCollapse) g_eyeOccl[e] = 1;
        /* An eye that just reopened still holds its stale frozen value; re-seed it
           so the both-eyes average is continuous across the reopen (no dip/step). */
        if (wasOccl && !g_eyeOccl[e])
            g_eyeS[e] = g_have_pupil ? (2.0f * g_lastMm - g_eyeS[1 - e]) : raw[e];
    }
    int valid[2];
    for (int e = 0; e < 2; e++)
        valid[e] = g_eyeHave[e] && !g_eyeOccl[e] && (now - g_eyeMs[e]) <= PUPIL_DET_FRESH_MS;
    float mm = 0.0f; int nd = 0;
    if (valid[0] && valid[1]) {
        mm = 0.5f * (g_eyeS[0] + g_eyeS[1]); nd = 2;
        g_pairMm = mm; g_pairEye[0] = g_eyeS[0]; g_pairEye[1] = g_eyeS[1]; g_pairHave = 1;
    } else if (valid[0] || valid[1]) {
        int e = valid[0] ? 0 : 1;
        /* Continue from the last both-eyes baseline and apply only the open eye's
           drift: no step when the other lid drops. */
        mm = g_pairHave ? g_pairMm + (g_eyeS[e] - g_pairEye[e]) : g_eyeS[e];
        nd = 1;
    }
    if (nd > 0) {
        /* The dilation envelope (min/max pupil) is what VRCFT normalizes against
           -- the module feeds it our window every frame -- so it must reflect the
           user's real range and nothing else. It therefore only learns from frames
           that are fully trustworthy: both eyes reading cleanly (never occluded)
           with both lids clearly open. Three things keep a bad value out:
             - the seed is the median of the first few CLEAN frames, not one frame;
             - an extreme has to persist for PUPIL_WINDOW_DWELL_MS AND still match
               the RAW reading when it is committed (the EMA tail of one bad
               detection outlives the dwell, which is how a 0.5 mm stray got in);
             - a stale extreme is healed back toward the recent p2/p98 (dil_heal).
           A locked range (dillock, or --dil-min/--dil-max) learns nothing. */
        int winClean = haveFace && valid[0] && valid[1] &&
                       (tail[T_LOpen] >= PUPIL_WINDOW_OPEN) &&
                       (tail[T_ROpen] >= PUPIL_WINDOW_OPEN);
        if (!g_have_pupil) {                            /* first reading: provisional window */
            if (!g_winLoaded) g_minMm = g_maxMm = mm;   /* a persisted/locked range is kept */
            g_winMinCand = g_winMaxCand = mm;
            g_winMinMs = g_winMaxMs = now;
            g_seedN = 0;
            g_seedStartMs = now;
            g_seedSampleMs = 0;
            g_seeded = g_winLoaded;                     /* a persisted range needs no seed */
            g_minTouchMs = g_maxTouchMs = now;
        } else if (!g_seeded) {
            if (winClean && now - g_seedSampleMs >= DIL_SEED_SAMPLE_MS &&
                g_seedN < DIL_SEED_BUF) {
                g_seedSampleMs = now;
                g_seedBuf[g_seedN++] = mm;
                if (g_seedN >= DIL_SEED_MIN) g_minMm = g_maxMm = median_of(g_seedBuf, g_seedN);
            }
            if (g_seedN >= DIL_SEED_MIN || now - g_seedStartMs >= DIL_SEED_TIMEOUT_MS) {
                g_seeded = 1;
                if (g_seedN > 0) {
                    g_minMm = g_maxMm = median_of(g_seedBuf, g_seedN);
                    g_winSaveable = 1;              /* a clean seed may be persisted */
                } else {
                    g_minMm = g_maxMm = mm;         /* no clean frame at all: learn, do not save */
                }
                g_winMinCand = g_winMaxCand = (g_lastMm > 0.0f) ? g_lastMm : mm;
                g_winMinMs = g_winMaxMs = now;
                g_minTouchMs = g_maxTouchMs = now;
                fprintf(stderr, "gxr_alvr: dilation seed %.3f mm (%d clean frame%s)\n",
                        (double)g_minMm, g_seedN, g_seedN == 1 ? "" : "s");
                if (g_winSaveable) dil_save();
            }
        } else if (winClean && !g_dilLock) {
            /* An extreme is only real if BOTH raw eye readings are present and the
               raw pair average is still extreme when the dwell expires; otherwise
               the smoothed tail of one bad detection is what gets committed. */
            int haveRaw = (raw[0] > 0.0f && raw[1] > 0.0f);
            float rawAvg = haveRaw ? 0.5f * (raw[0] + raw[1]) : 0.0f;
            int minReal = haveRaw && (rawAvg <= g_winMinCand + PUPIL_WINDOW_CONFIRM);
            int maxReal = haveRaw && (rawAvg >= g_winMaxCand - PUPIL_WINDOW_CONFIRM);
            if (mm < g_minMm) {
                if (mm < g_winMinCand - PUPIL_WINDOW_CONFIRM) { g_winMinCand = mm; g_winMinMs = now; }
                else if (mm < g_winMinCand) g_winMinCand = mm;
                if ((float)(now - g_winMinMs) >= PUPIL_WINDOW_DWELL_MS && minReal) {
                    g_minMm = g_winMinCand;
                    g_winSaveable = 1;
                    dil_save();
                }
            } else { g_winMinCand = mm; g_winMinMs = now; }
            if (mm > g_maxMm) {
                if (mm > g_winMaxCand + PUPIL_WINDOW_CONFIRM) { g_winMaxCand = mm; g_winMaxMs = now; }
                else if (mm > g_winMaxCand) g_winMaxCand = mm;
                if ((float)(now - g_winMaxMs) >= PUPIL_WINDOW_DWELL_MS && maxReal) {
                    g_maxMm = g_winMaxCand;
                    g_winSaveable = 1;
                    dil_save();
                }
            } else { g_winMaxCand = mm; g_winMaxMs = now; }
        }
        dil_history(mm, winClean, now);
        dil_heal(now);
        g_lastMm = mm;
        g_pupilAcceptMs = now;
        g_have_pupil = 1;
    }
    if (g_have_pupil) {
        float center = 0.5f * (g_minMm + g_maxMm);
        float half = 0.5f * fmaxf(g_maxMm - g_minMm, PUPIL_WINDOW_MIN_MM);
        float wideHalf = half / fmaxf(PUPIL_DILATION_GAIN, PUPIL_GAIN_MIN);
        float lo = center - wideHalf, hi = center + wideHalf;
        /* Never emit a window that excludes the emitted pupil: VRCFT pins
           dilation to 0 when pupil<=min and to 1 when pupil>=max. A LOCKED window
           is the exception: it is fixed on purpose, so pinning at the extremes is
           the honest behaviour of a range the user chose. */
        if (!g_dilLock) {
            float eps = fmaxf(PUPIL_WINDOW_MARGIN, 0.05f * (hi - lo));
            if (lo > g_lastMm - eps) lo = g_lastMm - eps;
            if (hi < g_lastMm + eps) hi = g_lastMm + eps;
        }
        g_lastMin = lo; g_lastMax = hi;
        tail[T_LPupil] = g_lastMm; tail[T_RPupil] = g_lastMm;
        tail[T_MinDil] = lo; tail[T_MaxDil] = hi;
    }
    if (g_verbose) {
        static long long lastpup = 0;
        if (now - lastpup > PUPIL_LOG_MS) {
            lastpup = now;
            g_printStartMs = now_ms();
            /* Per-detection dump: idx:d<mm>/c<conf>/x<centre-x>/a<age-ms>. The
               diameter here is UNCLAMPED so junk is visible. open= is the EMITTED
               openness (so the wink fold shows up here), closed= the raw input,
               wb= the wink-fold boost applied to it. */
            fprintf(stderr, "gxr_alvr: pupil mm=%.2f nd=%d min=%.2f max=%.2f open=%.2f/%.2f eye=%d%d oc=%d%d raw=%.2f/%.2f s=%.2f/%.2f closed=%.2f/%.2f wb=%.2f/%.2f lk=%d det=",
                    g_lastMm, nd, g_minMm, g_maxMm, tail[T_LOpen], tail[T_ROpen],
                    eyeOpen[0], eyeOpen[1], g_eyeOccl[0], g_eyeOccl[1],
                    raw[0], raw[1], g_eyeS[0], g_eyeS[1],
                    haveFace ? g_face[F_EYES_CLOSED_L] : -1.0f,
                    haveFace ? g_face[F_EYES_CLOSED_R] : -1.0f,
                    g_winkBoost[0], g_winkBoost[1], g_dilLock);
            for (int i = 0; i < MAX_DET; i++) {
                if (!g_det_ok[i]) continue;
                float dd = 2.0f * fmaxf(g_det[i][2], g_det[i][3]) * PUPIL_MM_SCALE;
                fprintf(stderr, "%d:d%.2f/c%.2f/x%.2f/a%lld ", i, dd, g_det_conf[i],
                        g_det[i][0], now - g_det_ms[i]);
            }
            fputc('\n', stderr);
            print_done();
        }
    }

    int haveEye = (now - g_eyedir_ms) <= FRESH_MS;
    if (haveEye) {
        /* The module maps Gaze.x <- the T_*Pitch slot and Gaze.y <- the T_*Yaw
           slot, and VRCFT's Gaze.x is HORIZONTAL / Gaze.y VERTICAL. So yaw must
           go into the *Pitch* slot and pitch into the *Yaw* slot; the straight
           assignment came out rotated 90 deg (up->right, right->up).
           Before mapping, each eye's raw direction is One-Euro filtered and then
           held while that eye's lid is down: the device does neither (its gaze
           filter is FILTER_TYPE_NONE and it has no lid gate), so a partly closed
           eyelid's corrupted direction used to go straight out. */
        float dt = (float)(now - g_gazeMs); g_gazeMs = now;
        if (dt <= 0.0f || dt > 500.0f) dt = (float)tx_period_ms();
        float ad = 1.0f / (1.0f + (1.0f / (TWO_PI_F * fmaxf(GAZE_DCUT, 0.01f))) / dt);
        /* Per-eye pupil size for the occlusion test, straight from the raw
           detections -- NOT the conf-filtered dilation path, because the fit
           confidence is unreliable in this firmware build. Largest candidate per
           eye, exactly what the offline validation used. A pupil frame is 250 ms
           old at worst, so the value is held briefly at use time rather than
           blinking the test on and off. */
        float gd[2] = { 0.0f, 0.0f };
        for (int i = 0; i < 4; i++) {                   /* 0/1 = left, 2/3 = right */
            if (!g_det_ok[i] || (now - g_det_ms[i]) > PUPIL_DET_FRESH_MS) continue;
            float ax = fmaxf(g_det[i][2], g_det[i][3]);
            if (ax <= 0.0f) continue;
            float dd = 2.0f * ax * PUPIL_MM_SCALE;
            if (dd > gd[i >> 1]) gd[i >> 1] = dd;
        }
        for (int e = 0; e < 2; e++)
            if (gd[e] > 0.0f) { g_gazeDe[e] = gd[e]; g_gazeDeMs[e] = now; }
        /* Seed the per-eye pupil baseline only from frames where the lid is
           clearly open and the pupil reads, so a squint, a blink or a bright dip
           cannot poison it. If this eye simply never opens that far, fall back to
           its own session best (floored) so a baseline still forms. */
        if (now - g_gazePupSampleMs >= GAZE_PUPIL_SAMPLE_MS) {
            g_gazePupSampleMs = now;
            for (int e = 0; e < 2; e++) {
                float open_e = haveFace ? (e ? tail[T_ROpen] : tail[T_LOpen]) : 1.0f;
                float need = fminf(GAZE_PUPIL_BASE_OPEN,
                                   fmaxf(0.98f * g_gazeOpenMax[e], 0.5f));
                if (!haveFace || open_e < need || g_gazeDe[e] <= 0.0f) continue;
                int k = g_gazePupIdx[e];
                g_gazePupRing[e][k] = g_gazeDe[e];
                g_gazePupRingMs[e][k] = now;
                g_gazePupIdx[e] = (k + 1) % GAZE_PUPIL_RING;
                if (g_gazePupN[e] < GAZE_PUPIL_RING) g_gazePupN[e]++;
                float tmp[GAZE_PUPIL_RING]; int m = 0;
                for (int j = 0; j < g_gazePupN[e]; j++) {
                    int q = (g_gazePupIdx[e] - 1 - j + 2 * GAZE_PUPIL_RING) % GAZE_PUPIL_RING;
                    if (now - g_gazePupRingMs[e][q] > GAZE_PUPIL_WIN_MS) continue;
                    tmp[m++] = g_gazePupRing[e][q];
                }
                if (m >= GAZE_PUPIL_MIN_N) {
                    qsort(tmp, m, sizeof(float), cmpf);
                    g_gazePupBase[e] = tmp[(int)(GAZE_PUPIL_PCT * (m - 1) + 0.5f)];
                }
            }
        }
        for (int e = 0; e < 2; e++) {
            if (!(g_eyedir_mask & (1 << e))) continue;
            const float *d = e ? g_Rdir : g_Ldir;
            float open = haveFace ? (e ? tail[T_ROpen] : tail[T_LOpen]) : 1.0f;
            if (haveFace && open > g_gazeOpenMax[e]) g_gazeOpenMax[e] = open;
            /* Can this eye's direction be believed right now? See the constant
               block: a pitch-guarded blink test OR a narrowed-lid + occluded-pupil
               test, each covering the other's false positive. The pitch used here
               is the raw, un-gated one, so it is still valid while frozen. */
            float rpitch = atan2f(-d[1], d[2]) * 57.29577951f;   /* + = up, deg */
            float base = g_gazePupBase[e];
            float de = (now - g_gazeDeMs[e] <= (long long)GAZE_DE_HOLD_MS) ? g_gazeDe[e] : 0.0f;
            float ratio = (base > 0.0f && de > 0.0f) ? (de / base) : -1.0f;
            g_gazeRatio[e] = ratio;
            int untrust = 0, soft = 0;
            if (open < GAZE_BLINK_SHUT && rpitch > GAZE_PITCH_GUARD)
                untrust = 1;                                   /* a real blink */
            else if (open < GAZE_LID_LOW && ratio >= 0.0f && ratio < GAZE_PUPIL_RATIO)
                untrust = 1;                                   /* narrow lid + occluded pupil */
            else if (open < GAZE_SOFT_OPEN && rpitch > GAZE_PITCH_GUARD)
                soft = 1;      /* narrowed lid, pupil still normal: the DNN direction
                                  is noisy but we cannot prove it is wrong, so smooth
                                  hard rather than freeze. The pitch guard keeps this
                                  off while looking down, where a low openness is pitch
                                  contamination and the gaze is fine. */
            if (untrust && g_gazeHave[e]) {
                g_gazeHeld[e] = 1;                      /* freeze: keep g_gazeOut */
            } else {
                g_gazeHeld[e] = 0;
                float fmin = soft ? GAZE_SOFT_FMIN : GAZE_FMIN;
                if (!g_gazeHave[e]) {
                    for (int a = 0; a < 3; a++) { g_gazeS[e][a] = d[a]; g_gazeDX[e][a] = 0.0f; }
                    g_gazeHave[e] = 1;
                } else {
                    for (int a = 0; a < 3; a++) {
                        float dx = (d[a] - g_gazeS[e][a]) / dt;
                        g_gazeDX[e][a] = ad * dx + (1.0f - ad) * g_gazeDX[e][a];
                        float fc = fmaxf(fmin + GAZE_BETA * fabsf(g_gazeDX[e][a]), 0.01f);
                        float fl = 1.0f / (1.0f + (1.0f / (TWO_PI_F * fc)) / dt);
                        g_gazeS[e][a] = fl * d[a] + (1.0f - fl) * g_gazeS[e][a];
                    }
                }
                for (int a = 0; a < 3; a++) g_gazeOut[e][a] = g_gazeS[e][a];
            }
            float gx, gy;
            gaze_map(g_gazeOut[e], &gx, &gy);
            if (e == 0) { tail[T_LPitch] = gx; tail[T_LYaw] = gy; }
            else        { tail[T_RPitch] = gx; tail[T_RYaw] = gy; }
        }
        static long long lastlog = 0;
        if (g_verbose && now - lastlog >= GAZE_LOG_MS) {
            lastlog = now;
            g_printStartMs = now_ms();
            float lx, ly, rx, ry;
            gaze_map(g_gazeOut[0], &lx, &ly); gaze_map(g_gazeOut[1], &rx, &ry);
            /* Fast per-eye trace. Ldir/Rdir are the RAW device vectors, Lg/Rg the
               emitted (filtered/held) gaze, held= is the trust gate, pu= is the
               pupil size relative to that eye's baseline (-1 = pupil unavailable),
               so a field capture shows exactly why an eye was gated. */
            fprintf(stderr, "gxr_alvr: gaze t=%lld ok=%d held=%d%d open=%.3f/%.3f pu=%.2f/%.2f "
                    "Ldir=%+.3f,%+.3f,%+.3f Rdir=%+.3f,%+.3f,%+.3f "
                    "Lg=%+.3f,%+.3f Rg=%+.3f,%+.3f\n",
                    now, g_eyedir_mask, g_gazeHeld[0], g_gazeHeld[1],
                    tail[T_LOpen], tail[T_ROpen], g_gazeRatio[0], g_gazeRatio[1],
                    g_Ldir[0], g_Ldir[1], g_Ldir[2],
                    g_Rdir[0], g_Rdir[1], g_Rdir[2],
                    lx, ly, rx, ry);
            print_done();
        }
    }

    /* 5) TongueRoll: the only tongue extra that tested clean (the 11-D model
       can't separate shape/twist reliably). The exact 11->5 mapper gives the
       DOFs the DOF-leak-free calibration readout needs. */
    if (g_tongue_extras && (now - g_tongue_ms) <= FRESH_MS) {
        float dof[TONGUE_DOF];
        tongue_mlp(g_tongue, dof);
        int pass = 1;
        if (g_tongue_gate > 0.0f)
            pass = (dof[0] >= g_tongue_gate) || (ue[UE_TongueOut] >= g_tongue_gate);
        if (pass) {
            float so = tongue_readout(g_tongue, dof, TR_ROLL_AXIS, TR_ROLL_DOF, TR_ROLL_INT);
            ue[UE_TongueRoll] = clampf(g_gain_roll * so, 0.0f, 1.0f);
        }
    }

    g_stateOk = 1;                 /* tx_send() transmits at the steady rate */
}

/* Returns 1 if the line was one of OUR probe events, 0 otherwise. trace_pipe is
   the GLOBAL pipe: when anything else has tracefs events enabled (a capture
   script, a vendor tracer) its lines land here too. Counting and timestamping
   only our own events keeps the heartbeat, the quiet detector and the transmit
   hold honest -- a foreign event must not look like the device feeding us. */
static int feed_line(const char *line) {
    int idx; float v[6];
    int eye; float d[3];
    float fv[FACE_N];
    float jv[4];
    float tv[TONGUE_N];

    if (parse_dir(line, &eye, d) == 0) {
        if (eye == 0) { memcpy(g_Ldir, d, 12); g_eyedir_mask |= 1; }
        else          { memcpy(g_Rdir, d, 12); g_eyedir_mask |= 2; }
        g_eyedir_ms = now_ms();
        g_dirty = 1;
        return 1;
    }
    if (parse_bs(line, fv) == 0) {
        memcpy(g_face, fv, sizeof(fv)); g_face_ms = now_ms();
        g_dirty = 1;
        return 1;
    }
    if (parse_jaw(line, jv) == 0) {
        memcpy(g_jaw, jv, sizeof(jv)); g_jaw_ms = now_ms();
        g_dirty = 1;
        return 1;
    }
    if (parse_tongue(line, tv) == 0) {
        memcpy(g_tongue, tv, sizeof(tv)); g_tongue_ms = now_ms();
        g_dirty = 1;
        return 1;
    }
    if (parse_pten(line, &idx, v) == 0) {
        if (idx >= 0 && idx < MAX_DET) {
            memcpy(g_det[idx], v, sizeof(v));
            g_det_conf[idx] = v[4];
            g_det_ms[idx] = now_ms();
            g_det_ok[idx] = 1;
        }
        g_pupil_ms = now_ms();
        g_dirty = 1;
        return 1;
    }
    return 0;
}

